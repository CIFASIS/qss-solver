#!/bin/bash
#===================================================================================
#
# 				 FILE: generate_conf.sh
#
# 				USAGE: generate_conf
#
# 	DESCRIPTION: Generate an environment.d file for qss-solver app so that both 
#                Ubuntu and Kubuntu load these variables. 
#
#    PARAMETERS: --- 
#  REQUIREMENTS: ---
#         NOTES: ---
#        AUTHOR: Joaquin Fernandez, joaquin.f.fernandez@gmail.com
#       PROJECT: QSS Solver
#       VERSION: 6.0.0
#===================================================================================

ENV_DIR="$HOME/.config/environment.d"
ENV_FILE="$ENV_DIR/qss-solver.conf"
BASHRC="$HOME/.bashrc"

MMOC_BASE="$HOME/qss-solver"

VARIABLES=(
    "MMOC_PATH=$MMOC_BASE"
    "MMOC_SRC=$MMOC_BASE/src"
    "MMOC_DOC=$MMOC_BASE/doc"
    "MMOC_LIBS=$MMOC_BASE/lib"
    "MMOC_BUILD=$MMOC_BASE/build"
    "MMOC_MODELS=$MMOC_BASE/models"
    "MMOC_OUTPUT=$MMOC_BASE/output"
    "MMOC_BIN=$MMOC_BASE/bin"
    "MMOC_PACKAGES=$MMOC_BASE/packages"
    "MMOC_LIBRARIES=$MMOC_BASE/lib"
    "MMOC_TESTS=$MMOC_BASE/src/test-suite"
    "MMOC_ENGINE=$MMOC_BASE/src/engine/"
    "MMOC_INCLUDE=$MMOC_BASE/src/usr/include"
)

echo "Cleaning and updating $ENV_FILE..."
mkdir -p "$ENV_DIR"

{
    echo "# Generated by QSS Setup Script - $(date)"
    for entry in "${VARIABLES[@]}"; do
        echo "$entry"
    done
} > "$ENV_FILE"

echo "Syncing $BASHRC..."

for entry in "${VARIABLES[@]}"; do
    key=$(echo "$entry" | cut -d'=' -f1)
    val=$(echo "$entry" | cut -d'=' -f2)
    
    # Only add if the specific export doesn't already exist
    if ! grep -q "export $key=" "$BASHRC"; then
        echo "export $key=$val" >> "$BASHRC"
        echo "[+] Added $key to bashrc"
    fi
done

echo "Injecting into current GUI session..."

CURRENT_SESSION_VARS=$(systemctl --user show-environment)

for entry in "${VARIABLES[@]}"; do
    key=$(echo "$entry" | cut -d'=' -f1)
    val=$(echo "$entry" | cut -d'=' -f2)
    
    # Check if current session value matches the target value
    if ! echo "$CURRENT_SESSION_VARS" | grep -q "^$key=$val$"; then
        systemctl --user import-environment "$key=$val"
        dbus-update-activation-environment --systemd "$key=$val"
        echo "[✓] Injected $key"
    fi
done

echo "------------------------------------------------"
echo "Done! QSS/MMOC environment is optimized and live."